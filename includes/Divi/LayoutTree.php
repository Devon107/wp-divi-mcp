<?php
/**
 * JSON layout tree -> Divi 5 blocks (the format Claude sends).
 *
 * Pure PHP, no WordPress dependency, so it also runs in CLI tooling.
 *
 * @package WPDM
 */

namespace WPDM\Divi;

/**
 * Builds D5 blocks from a JSON tree that mirrors the D5 / Patterns calls.
 *
 * Tree: {builder_version?, theme?, global_colors?, global_variables?, custom_css?, blocks: [node]}.
 *
 * Nodes:
 * - `{"<helper>": {...args, "children"?: [node]}}` calls D5::<helper>(). Args are the PHP/Python
 *   parameter names: required parameters are bound by name (ReflectionMethod), everything
 *   else goes to the trailing `$opts`; `children` are the variadic children.
 * - `{"pattern": "<name>", "args": {...}}` calls Patterns::<name>() the same way. The tree's
 *   `theme` is passed to every pattern; `args.theme` builds a Theme merged over it.
 * - `{"block": "divi/<name>", "attrs"?: {...}, "children"?: [node]}` calls D5::block().
 *
 * Value helpers are resolved anywhere inside args/attrs (see VALUE_HELPERS). Their keys carry
 * a `$` prefix (`{"$rv": ...}`, `{"$fa": "&#xf19d;", "weight": "400"}`) so they never collide
 * with real Divi attribute keys (`decoration.font.font`, `border.*.radius`...), which are always
 * plain data. An object is a helper call when exactly one of its keys is a `$helper` and every
 * other key is one of that helper's sibling keys (`$fa` + `weight`, `$color_var` + `opacity`).
 * Any other key next to a `$helper`, or two `$helper` keys in one object, is a LayoutError.
 * `{"$literal": X}` yields X untouched.
 *
 * Structure: top-level blocks are sections, rows go directly in sections, columns (and the
 * card patterns, which return columns) go directly in a row / grid_row. Errors are
 * LayoutError with the path of the offending node.
 *
 * The JSON Schema (schema/layout.schema.json) is generated by tools/gen-layout-schema.php.
 */
class LayoutTree {

	/**
	 * D5 helpers usable as nodes (each is a D5 method of the same name).
	 */
	const HELPERS = array(
		'section',
		'row',
		'grid_row',
		'column',
		'group',
		'text',
		'image',
		'link',
		'icon',
		'heading',
		'button',
		'blurb',
		'code',
		'toggle',
		'accordion',
		'accordion_item',
		'number_counter',
		'divider',
		'cta',
		'testimonial',
		'team_member',
		'contact_form',
		'contact_field',
		'timeline',
		'timeline_item',
		'icon_list',
		'icon_list_item',
		'social_follow',
		'social_network',
		'breadcrumbs',
	);

	/**
	 * Prefix of value helper keys in the tree.
	 */
	const PREFIX = '$';

	/**
	 * Value helpers resolved inside args/attrs (written with PREFIX: "$rv") => D5 method.
	 */
	const VALUE_HELPERS = array(
		'rv'          => 'rv',
		'box'         => 'box',
		'radius'      => 'radius',
		'color_var'   => 'color_var',
		'content_var' => 'content_var',
		'fa'          => 'fa_icon',
		'divi_icon'   => 'divi_icon',
		'font'        => 'font',
		'flex'        => 'flex',
		'grid'        => 'grid',
		'card'        => 'card',
		'module_deco' => 'module_deco',
		'merge'       => 'merge',
	);

	/**
	 * Keys allowed next to a value helper's key in the same object.
	 */
	const VALUE_SIBLINGS = array(
		'fa'        => array( 'weight' ),
		'color_var' => array( 'opacity' ),
	);

	/**
	 * Patterns that return a column (a card): only allowed directly in a row / grid_row.
	 */
	const CARD_PATTERNS = array( 'icon_card', 'media_card', 'person_card', 'testimonial_card', 'numbered_card', 'step_card', 'stat_card' );

	/**
	 * Block names of the structural helpers (others are modules for placement purposes).
	 */
	const STRUCTURE = array(
		'section'  => 'divi/section',
		'row'      => 'divi/row',
		'grid_row' => 'divi/row',
		'column'   => 'divi/column',
		'group'    => 'divi/group',
	);

	const TOP_KEYS = array( 'builder_version', 'theme', 'global_colors', 'global_variables', 'custom_css', 'blocks' );

	const SCHEMA_FILE = __DIR__ . '/schema/layout.schema.json';

	/**
	 * @var array|null Cached schema.
	 */
	private static $schema = null;

	/**
	 * @var string[]|null Cached pattern names.
	 */
	private static $patterns = null;

	/**
	 * @var array Top-level theme overrides (value helpers resolved).
	 */
	private $theme_overrides = array();

	/**
	 * @var Theme|null Top-level theme (null = Patterns' default Theme).
	 */
	private $theme = null;

	/**
	 * Build a layout tree.
	 *
	 * Accepts json_decode() output in either mode (assoc arrays or stdClass objects; decode
	 * with objects to keep empty `{}` distinct from `[]`).
	 *
	 * @param array $tree Tree.
	 * @return array{blocks: Block[], content: string, envelope: array, images: string[]}
	 * @throws LayoutError On any problem in the tree.
	 */
	public static function build( array $tree ): array {
		$tree = self::normalize( $tree );
		foreach ( $tree as $key => $unused ) {
			if ( ! in_array( $key, self::TOP_KEYS, true ) ) {
				throw new LayoutError( (string) $key, "unknown top-level key '{$key}'. Allowed: " . implode( ', ', self::TOP_KEYS ) );
			}
		}
		if ( ! array_key_exists( 'blocks', $tree ) ) {
			throw new LayoutError( 'blocks', 'missing: the tree needs "blocks": [ {"section": {...}}, ... ]' );
		}
		if ( ! self::is_list_value( $tree['blocks'] ) || array() === $tree['blocks'] ) {
			throw new LayoutError( 'blocks', 'expected a non-empty list of section nodes; found ' . self::describe( $tree['blocks'] ) );
		}
		if ( array_key_exists( 'builder_version', $tree ) && ( ! is_string( $tree['builder_version'] ) || '' === $tree['builder_version'] ) ) {
			throw new LayoutError( 'builder_version', 'expected a Divi version string like "5.14.0"; found ' . self::describe( $tree['builder_version'] ) );
		}
		foreach ( array( 'global_colors', 'global_variables' ) as $key ) {
			if ( isset( $tree[ $key ] ) && ! self::is_list_value( $tree[ $key ] ) ) {
				throw new LayoutError( $key, 'expected a list; found ' . self::describe( $tree[ $key ] ) );
			}
		}
		if ( isset( $tree['custom_css'] ) && ! is_string( $tree['custom_css'] ) ) {
			throw new LayoutError( 'custom_css', 'expected a CSS string; found ' . self::describe( $tree['custom_css'] ) );
		}

		$previous = D5::builder_version();
		try {
			if ( isset( $tree['builder_version'] ) ) {
				D5::set_builder_version( $tree['builder_version'] );
			}
			$builder = new self();
			if ( isset( $tree['theme'] ) ) {
				$builder->theme_overrides = $builder->theme_array( $tree['theme'], 'theme' );
				$builder->theme           = self::make_theme( $builder->theme_overrides, 'theme' );
			}
			$blocks = array();
			foreach ( $tree['blocks'] as $i => $node ) {
				foreach ( $builder->node( $node, "blocks[{$i}]", null ) as $block ) {
					$blocks[] = $block;
				}
			}
		} finally {
			D5::set_builder_version( $previous );
		}

		return array(
			'blocks'   => $blocks,
			'content'  => D5::post_content( $blocks ),
			'envelope' => D5::layout_export(
				$blocks,
				array(
					'global_colors'    => isset( $tree['global_colors'] ) ? $tree['global_colors'] : null,
					'global_variables' => isset( $tree['global_variables'] ) ? $tree['global_variables'] : null,
					'custom_css'       => isset( $tree['custom_css'] ) ? $tree['custom_css'] : '',
				)
			),
			'images'   => D5::find_image_urls( $blocks ),
		);
	}

	/**
	 * The layout JSON Schema (draft 2020-12), loaded once.
	 *
	 * @return array
	 */
	public static function schema(): array {
		if ( null === self::$schema ) {
			$raw    = file_get_contents( self::SCHEMA_FILE ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents
			$schema = false === $raw ? null : json_decode( $raw, true );
			if ( ! is_array( $schema ) ) {
				throw new \RuntimeException( 'Cannot read ' . self::SCHEMA_FILE );
			}
			self::$schema = $schema;
		}
		return self::$schema;
	}

	/**
	 * Node helper names.
	 *
	 * @return string[]
	 */
	public static function helpers(): array {
		return self::HELPERS;
	}

	/**
	 * Pattern names: the public static methods of Patterns, in declaration order.
	 *
	 * @return string[]
	 */
	public static function patterns(): array {
		if ( null === self::$patterns ) {
			$names = array();
			$class = new \ReflectionClass( Patterns::class );
			foreach ( $class->getMethods( \ReflectionMethod::IS_PUBLIC ) as $m ) {
				if ( $m->isStatic() && Patterns::class === $m->getDeclaringClass()->getName() ) {
					$names[] = $m->getName();
				}
			}
			self::$patterns = $names;
		}
		return self::$patterns;
	}

	/**
	 * Value helper names, without the "$" prefix.
	 *
	 * @return string[]
	 */
	public static function value_helpers(): array {
		return array_keys( self::VALUE_HELPERS );
	}

	// ------------------------------------------------------------------ //
	// Nodes
	// ------------------------------------------------------------------ //

	/**
	 * Build one node.
	 *
	 * @param mixed      $node   Node.
	 * @param string     $path   Path of the node.
	 * @param array|null $parent Parent ['name' => block name, 'label' => kind]; null = top level.
	 * @return Block[]
	 */
	private function node( $node, $path, $parent ) {
		if ( ! self::is_object_value( $node ) || self::is_empty( $node ) ) {
			throw new LayoutError( $path, 'expected a node object: {"<helper>": {...}}, {"pattern": "<name>", "args": {...}} or {"block": "divi/<name>", ...}; found ' . self::describe( $node ) );
		}
		$node = self::to_array( $node );
		if ( array_key_exists( 'pattern', $node ) ) {
			return $this->pattern_node( $node, $path, $parent );
		}
		if ( array_key_exists( 'block', $node ) ) {
			return array( $this->block_node( $node, $path, $parent ) );
		}
		if ( 1 !== count( $node ) ) {
			throw new LayoutError( $path, 'a helper node has exactly one key, the helper name, e.g. {"text": {"html": "<p>Hi</p>"}}; found keys ' . implode( ', ', array_keys( $node ) ) );
		}
		$kind = (string) key( $node );
		if ( ! in_array( $kind, self::HELPERS, true ) ) {
			throw new LayoutError( $path, self::unknown_kind_message( $kind ) );
		}
		return array( $this->helper_node( $kind, $node[ $kind ], $path, $parent ) );
	}

	/**
	 * `{"<helper>": {...}}`.
	 *
	 * @param string     $kind   Helper.
	 * @param mixed      $args   Args.
	 * @param string     $path   Node path.
	 * @param array|null $parent Parent.
	 * @return Block
	 */
	private function helper_node( $kind, $args, $path, $parent ) {
		$npath = "{$path}.{$kind}";
		$name  = isset( self::STRUCTURE[ $kind ] ) ? self::STRUCTURE[ $kind ] : 'divi/' . $kind;
		self::check_placement( $name, $kind, $npath, $parent );
		$args     = $this->args_object( $args, $npath, $kind );
		$method   = new \ReflectionMethod( D5::class, $kind );
		$variadic = self::is_variadic( $method );
		if ( array_key_exists( 'children', $args ) && ! $variadic ) {
			throw new LayoutError( "{$npath}.children", "{$kind} does not take children (it is a self-contained module); remove \"children\"" );
		}
		self::check_keys( $args, self::allowed_args( 'node_' . $kind ), $npath, $kind );

		$children = array();
		if ( array_key_exists( 'children', $args ) ) {
			$children = $this->children( $args['children'], "{$npath}.children", $name, $kind );
		}
		unset( $args['children'] );
		$values = $this->resolve_args( $args, $npath );

		$call = $variadic ? array_merge( $children, array( $values ) ) : self::bind( $method, $values, $npath, $kind, null );
		return self::invoke( $method, $call, $npath );
	}

	/**
	 * `{"pattern": "<name>", "args": {...}}`.
	 *
	 * @param array      $node   Node.
	 * @param string     $path   Node path.
	 * @param array|null $parent Parent.
	 * @return Block[]
	 */
	private function pattern_node( array $node, $path, $parent ) {
		$name = $node['pattern'];
		if ( ! is_string( $name ) || ! in_array( $name, self::patterns(), true ) ) {
			$label = is_string( $name ) ? $name : self::describe( $name );
			throw new LayoutError( "{$path}.pattern", "unknown pattern '{$label}'." . self::suggest( $label, self::patterns() ) . ' Patterns: ' . implode( ', ', self::patterns() ) );
		}
		$ppath = "{$path}.pattern({$name})";
		foreach ( $node as $key => $unused ) {
			if ( 'pattern' !== $key && 'args' !== $key ) {
				throw new LayoutError( $ppath, "unknown key '{$key}' in a pattern node; use {\"pattern\": \"{$name}\", \"args\": {...}}" . ( 'children' === $key ? ' (patterns take no children)' : '' ) );
			}
		}
		$is_card = in_array( $name, self::CARD_PATTERNS, true );
		self::check_placement( $is_card ? 'divi/column' : 'divi/' . $name, $name, $ppath, $parent );

		$args = $this->args_object( array_key_exists( 'args', $node ) ? $node['args'] : array(), "{$ppath}.args", $name );
		self::check_keys( $args, self::allowed_args( 'pattern_' . $name ), "{$ppath}.args", $name );
		$theme = $this->theme;
		if ( array_key_exists( 'theme', $args ) ) {
			$own   = $this->theme_array( $args['theme'], "{$ppath}.args.theme" );
			$theme = self::make_theme( array_merge( $this->theme_overrides, $own ), "{$ppath}.args.theme" );
			unset( $args['theme'] );
		}
		$values = $this->resolve_args( $args, "{$ppath}.args" );
		$method = new \ReflectionMethod( Patterns::class, $name );
		$result = self::invoke( $method, self::bind( $method, $values, "{$ppath}.args", $name, $theme ), $ppath );
		return is_array( $result ) ? $result : array( $result );
	}

	/**
	 * `{"block": "divi/<name>", "attrs"?: {...}, "children"?: [...]}`.
	 *
	 * @param array      $node   Node.
	 * @param string     $path   Node path.
	 * @param array|null $parent Parent.
	 * @return Block
	 */
	private function block_node( array $node, $path, $parent ) {
		$name  = $node['block'];
		$label = is_string( $name ) ? $name : self::describe( $name );
		$bpath = "{$path}.block({$label})";
		if ( ! is_string( $name ) || 0 !== strpos( $name, 'divi/' ) ) {
			throw new LayoutError( $bpath, 'expected a block name starting with "divi/", e.g. "divi/text"; found ' . self::describe( $name ) );
		}
		foreach ( $node as $key => $unused ) {
			if ( ! in_array( $key, array( 'block', 'attrs', 'children' ), true ) ) {
				throw new LayoutError( $bpath, "unknown key '{$key}' in a block node. Allowed: block, attrs, children" );
			}
		}
		self::check_placement( $name, $name, $bpath, $parent );
		$attrs = array_key_exists( 'attrs', $node ) ? $node['attrs'] : null;
		if ( null !== $attrs && ! self::is_object_value( $attrs ) ) {
			throw new LayoutError( "{$bpath}.attrs", 'expected an object of Divi attributes; found ' . self::describe( $attrs ) );
		}
		$children = null;
		if ( array_key_exists( 'children', $node ) ) {
			$children = $this->children( $node['children'], "{$bpath}.children", $name, $name );
		}
		$attrs = null === $attrs ? null : $this->resolve( $attrs, "{$bpath}.attrs" );
		if ( null !== $attrs && ! self::is_object_value( $attrs ) ) {
			throw new LayoutError( "{$bpath}.attrs", 'expected attrs to resolve to an object; found ' . self::describe( $attrs ) );
		}
		$method = new \ReflectionMethod( D5::class, 'block' );
		return self::invoke( $method, array( $name, $attrs, $children ), $bpath );
	}

	/**
	 * Build a children list.
	 *
	 * @param mixed  $nodes Nodes.
	 * @param string $path  Path of the list.
	 * @param string $name  Parent block name.
	 * @param string $label Parent kind.
	 * @return Block[]
	 */
	private function children( $nodes, $path, $name, $label ) {
		if ( ! self::is_list_value( $nodes ) ) {
			throw new LayoutError( $path, 'expected a list of nodes; found ' . self::describe( $nodes ) );
		}
		$parent = array(
			'name'  => $name,
			'label' => $label,
		);
		$out    = array();
		foreach ( $nodes as $i => $child ) {
			foreach ( $this->node( $child, "{$path}[{$i}]", $parent ) as $block ) {
				$out[] = $block;
			}
		}
		return $out;
	}

	/**
	 * Enforce the section > row > column nesting.
	 *
	 * @param string     $name   Block name the node produces.
	 * @param string     $label  Node kind (helper, pattern or block name).
	 * @param string     $path   Node path.
	 * @param array|null $parent Parent.
	 * @return void
	 */
	private static function check_placement( $name, $label, $path, $parent ) {
		$is_card = in_array( $label, self::CARD_PATTERNS, true );
		if ( null === $parent ) {
			if ( 'divi/section' !== $name ) {
				throw new LayoutError( $path, "top-level blocks must be sections (Theme Builder headers/footers too); found {$label}. Wrap it: {\"section\": {\"children\": [{\"row\": {\"children\": [{\"column\": {\"children\": [...]}}]}}]}}" );
			}
			return;
		}
		$where = "inside {$parent['label']}";
		if ( 'divi/section' === $name ) {
			throw new LayoutError( $path, "sections are only allowed at the top level of \"blocks\"; found one {$where}" );
		}
		if ( 'divi/row' === $name && 'divi/section' !== $parent['name'] ) {
			throw new LayoutError( $path, "{$label} is only allowed directly inside a section; found {$where}" );
		}
		if ( 'divi/column' === $name && 'divi/row' !== $parent['name'] ) {
			if ( $is_card ) {
				throw new LayoutError( $path, "{$label} is a card pattern and returns a column, so it goes directly in the children of a row or grid_row; found {$where}. Move it up into the row/grid_row (no wrapping column)" );
			}
			throw new LayoutError( $path, "{$label} is only allowed directly inside a row or grid_row; found {$where}" );
		}
		if ( 'divi/row' === $parent['name'] && 'divi/column' !== $name ) {
			throw new LayoutError( $path, "a row/grid_row holds only columns (column or card patterns); found {$label}. Wrap it in a column: {\"column\": {\"children\": [...]}}" );
		}
	}

	// ------------------------------------------------------------------ //
	// Arguments
	// ------------------------------------------------------------------ //

	/**
	 * Args object of a node (empty / missing = no args).
	 *
	 * @param mixed  $args  Args.
	 * @param string $path  Path.
	 * @param string $label Kind.
	 * @return array
	 */
	private function args_object( $args, $path, $label ) {
		if ( null === $args || self::is_empty( $args ) ) {
			return array();
		}
		if ( ! self::is_object_value( $args ) ) {
			throw new LayoutError( $path, "expected an object of {$label} args (parameter names as keys); found " . self::describe( $args ) );
		}
		return self::to_array( $args );
	}

	/**
	 * Resolve value helpers in every arg.
	 *
	 * @param array  $args Args.
	 * @param string $path Path of the args object.
	 * @return array
	 */
	private function resolve_args( array $args, $path ) {
		$out = array();
		foreach ( $args as $key => $value ) {
			$out[ $key ] = $this->resolve( $value, "{$path}.{$key}" );
		}
		return $out;
	}

	/**
	 * Map named args to a method's parameters: positional parameters by name, the rest
	 * into the trailing array parameter ($opts, $more, $groups); a Theme parameter gets $theme.
	 *
	 * @param \ReflectionMethod $method Method.
	 * @param array             $values Named args.
	 * @param string            $path   Path of the args object.
	 * @param string            $label  Kind.
	 * @param Theme|null        $theme  Theme for a Theme parameter.
	 * @return array Positional arguments.
	 */
	private static function bind( \ReflectionMethod $method, array $values, $path, $label, $theme ) {
		$params = $method->getParameters();
		$rest   = null;
		$last   = end( $params );
		if ( $last && ! $last->isVariadic() && self::type_name( $last ) === 'array' ) {
			$rest = $last->getName();
		}
		$required = array();
		foreach ( $params as $p ) {
			if ( ! $p->isOptional() ) {
				$required[] = $p->getName();
			}
		}
		$call = array();
		foreach ( $params as $p ) {
			$name = $p->getName();
			if ( $name === $rest ) {
				break;
			}
			if ( self::type_name( $p ) === Theme::class ) {
				$call[] = $theme;
				continue;
			}
			if ( array_key_exists( $name, $values ) ) {
				$call[] = $values[ $name ];
				unset( $values[ $name ] );
			} elseif ( $p->isDefaultValueAvailable() ) {
				$call[] = $p->getDefaultValue();
			} else {
				throw new LayoutError( "{$path}.{$name}", "missing required arg '{$name}'. {$label} needs: " . implode( ', ', $required ) );
			}
		}
		if ( null !== $rest ) {
			$call[] = $values;
		} elseif ( $values ) {
			$keys = array_keys( $values );
			throw new LayoutError( "{$path}.{$keys[0]}", "unknown arg '{$keys[0]}' for {$label}" );
		}
		return $call;
	}

	/**
	 * Call a D5/Patterns method, wrapping its InvalidArgumentException/TypeError with the path.
	 *
	 * @param \ReflectionMethod $method Method.
	 * @param array             $args   Positional arguments.
	 * @param string            $path   Path.
	 * @return mixed
	 */
	private static function invoke( \ReflectionMethod $method, array $args, $path ) {
		try {
			return $method->invoke( null, ...$args );
		} catch ( LayoutError $e ) {
			throw $e;
		} catch ( \InvalidArgumentException $e ) {
			throw new LayoutError( $path, $e->getMessage(), $e );
		} catch ( \TypeError $e ) {
			throw new LayoutError( $path, 'wrong value type for ' . $method->getName() . '(): ' . $e->getMessage(), $e );
		}
	}

	/**
	 * Reject arg keys not in the schema for this kind (before building children).
	 *
	 * @param array         $args    Args.
	 * @param string[]|null $allowed Allowed keys (null = no check).
	 * @param string        $path    Path of the args object.
	 * @param string        $label   Kind.
	 * @return void
	 */
	private static function check_keys( array $args, $allowed, $path, $label ) {
		if ( null === $allowed ) {
			return;
		}
		foreach ( $args as $key => $unused ) {
			if ( ! in_array( (string) $key, $allowed, true ) ) {
				throw new LayoutError( $path, "unknown arg '{$key}' for {$label}." . self::suggest( (string) $key, $allowed ) . ' Allowed args: ' . implode( ', ', $allowed ) . '.' );
			}
		}
	}

	/**
	 * Allowed arg names of a schema definition.
	 *
	 * @param string $def $defs key (node_x, pattern_x, value_x).
	 * @return string[]|null
	 */
	private static function allowed_args( $def ) {
		$defs = self::schema()['$defs'];
		if ( ! isset( $defs[ $def ]['properties'] ) ) {
			return null;
		}
		$props = $defs[ $def ]['properties'];
		if ( 0 === strpos( $def, 'pattern_' ) ) {
			$inner = isset( $props['args']['properties'] ) ? $props['args']['properties'] : null;
		} else {
			$key   = substr( $def, strpos( $def, '_' ) + 1 );
			$key   = 0 === strpos( $def, 'value_' ) ? self::PREFIX . $key : $key;
			$inner = isset( $props[ $key ]['properties'] ) ? $props[ $key ]['properties'] : null;
		}
		return null === $inner ? null : array_map( 'strval', array_keys( $inner ) );
	}

