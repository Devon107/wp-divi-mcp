	/**
	 * Message for an unknown helper key.
	 *
	 * @param string $kind Key.
	 * @return string
	 */
	private static function unknown_kind_message( $kind ) {
		if ( in_array( $kind, self::patterns(), true ) ) {
			return "'{$kind}' is a pattern, not a helper: write {\"pattern\": \"{$kind}\", \"args\": {...}}";
		}
		if ( 0 === strpos( $kind, self::PREFIX ) || array_key_exists( $kind, self::VALUE_HELPERS ) ) {
			return "'{$kind}' is not a node (value helpers such as \$rv go inside args/attrs)";
		}
		return "unknown node kind '{$kind}'." . self::suggest( $kind, array_merge( self::HELPERS, self::patterns() ) )
			. ' Expected a helper (' . implode( ', ', self::HELPERS ) . '), {"pattern": "<name>", "args": {...}} or {"block": "divi/<name>", "attrs": {...}}';
	}

	/**
	 * " Did you mean 'x'?" for the closest candidate, or "".
	 *
	 * @param string   $word       Word.
	 * @param string[] $candidates Candidates.
	 * @return string
	 */
	private static function suggest( $word, array $candidates ) {
		$best  = null;
		$score = PHP_INT_MAX;
		foreach ( $candidates as $c ) {
			$d = levenshtein( $word, $c );
			if ( $d < $score ) {
				$best  = $c;
				$score = $d;
			}
		}
		if ( null === $best || $score > max( 2, (int) ( strlen( $word ) / 3 ) ) ) {
			$best = null;
			foreach ( $candidates as $c ) {
				if ( strlen( $word ) >= 3 && 0 === strpos( $c, $word ) ) {
					$best = $c; // "icon" -> "icon_value".
					break;
				}
			}
		}
		return null !== $best ? " Did you mean '{$best}'?" : '';
	}

	/**
	 * Short description of a value for messages.
	 *
	 * @param mixed $value Value.
	 * @return string
	 */
	private static function describe( $value ) {
		if ( null === $value ) {
			return 'null';
		}
		if ( is_bool( $value ) ) {
			return $value ? 'true' : 'false';
		}
		if ( is_int( $value ) || is_float( $value ) ) {
			return (string) $value;
		}
		if ( is_string( $value ) ) {
			return strlen( $value ) > 40 ? 'string "' . substr( $value, 0, 37 ) . '..."' : 'string "' . $value . '"';
		}
		if ( self::is_empty( $value ) ) {
			return 'an empty object/list';
		}
		if ( is_array( $value ) && D5::is_list( $value ) ) {
			return 'a list of ' . count( $value );
		}
		if ( self::is_object_value( $value ) ) {
			return 'an object with keys ' . implode( ', ', array_keys( self::to_array( $value ) ) );
		}
		return gettype( $value );
	}

	/**
	 * Recursively turn stdClass into arrays; an empty stdClass stays (it encodes as {}).
	 *
	 * @param mixed $value Value.
	 * @return mixed
	 */
	private static function normalize( $value ) {
		if ( $value instanceof \stdClass ) {
			$vars = get_object_vars( $value );
			if ( ! $vars ) {
				return $value;
			}
			$value = $vars;
		}
		if ( is_array( $value ) ) {
			foreach ( $value as $key => $item ) {
				$value[ $key ] = self::normalize( $item );
			}
		}
		return $value;
	}

	/**
	 * JSON object (or empty array/stdClass, which may be either)?
	 *
	 * @param mixed $value Value.
	 * @return bool
	 */
	private static function is_object_value( $value ) {
		return $value instanceof \stdClass || ( is_array( $value ) && ( array() === $value || ! D5::is_list( $value ) ) );
	}

	/**
	 * JSON array (an empty array counts)?
	 *
	 * @param mixed $value Value.
	 * @return bool
	 */
	private static function is_list_value( $value ) {
		return is_array( $value ) && D5::is_list( $value );
	}

	/**
	 * Empty array or empty stdClass?
	 *
	 * @param mixed $value Value.
	 * @return bool
	 */
	private static function is_empty( $value ) {
		return array() === $value || ( $value instanceof \stdClass && ! get_object_vars( $value ) );
	}

	/**
	 * Object as an array.
	 *
	 * @param array|\stdClass $value Value.
	 * @return array
	 */
	private static function to_array( $value ) {
		return $value instanceof \stdClass ? get_object_vars( $value ) : $value;
	}

	/**
	 * Does the method take variadic children?
	 *
	 * @param \ReflectionMethod $method Method.
	 * @return bool
	 */
	private static function is_variadic( \ReflectionMethod $method ) {
		$params = $method->getParameters();
		return $params && end( $params )->isVariadic();
	}

	/**
	 * Declared type name of a parameter, or "".
	 *
	 * @param \ReflectionParameter $p Parameter.
	 * @return string
	 */
	private static function type_name( \ReflectionParameter $p ) {
		$type = $p->getType();
		return $type instanceof \ReflectionNamedType ? $type->getName() : '';
	}
