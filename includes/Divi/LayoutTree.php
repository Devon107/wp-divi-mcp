	/**
	 * Theme overrides object with value helpers resolved.
	 *
	 * @param mixed  $value Value.
	 * @param string $path  Path.
	 * @return array
	 */
	private function theme_array( $value, $path ) {
		if ( self::is_empty( $value ) ) {
			return array();
		}
		if ( ! self::is_object_value( $value ) ) {
			throw new LayoutError( $path, 'expected an object of Theme tokens, e.g. {"accent": "#0043ff"}; found ' . self::describe( $value ) );
		}
		return self::to_array( $this->resolve( $value, $path ) );
	}

	/**
	 * Theme::from_array() with the error wrapped.
	 *
	 * @param array  $overrides Overrides.
	 * @param string $path      Path.
	 * @return Theme
	 */
	private static function make_theme( array $overrides, $path ) {
		try {
			return Theme::from_array( $overrides );
		} catch ( \InvalidArgumentException $e ) {
			$tokens = array_keys( get_class_vars( Theme::class ) );
			throw new LayoutError( $path, $e->getMessage() . '. Tokens: ' . implode( ', ', $tokens ), $e );
		}
	}

